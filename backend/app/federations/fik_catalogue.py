"""The FIK affiliate list bundled with each release, and its sync into the
Federation catalogue (#613).

`fik_affiliates.json` is generated by `scripts/update_fik_affiliates.py` and
reviewed in a PR like any other change; instances never contact the FIK.
`kendo-migrate` calls `sync` after `alembic upgrade head`, on every run.

A FIK row's fields have one owner each. The sync owns `name`, `website`,
`continental_grouping`, `type` and `iso_code`, and overwrites them; the Admin
owns `abbreviation`, `is_pinned` and `is_active`, which the sync only sets on
insert. An affiliate that leaves the list is deactivated, never deleted:
Federation Memberships still reference it. Rows the Admin added (`source`
null) are never touched.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.federations.db_models import Federation

SOURCE = "fik"
CATALOGUE_PATH = Path(__file__).with_name("fik_affiliates.json")

FIELDS = (
    "source_key",
    "name",
    "iso_code",
    "continental_grouping",
    "website",
    "type",
)
TYPES = frozenset({"National", "Special Status", "Regional Body", "Global Body"})
GROUPINGS = frozenset({"Africa", "Asia", "Europe", "Oceania", "Pan-Am", "Global"})
_ISO = re.compile(r"^[A-Z]{2}(-[A-Z0-9]{1,3})?$")
_SLUG = re.compile(r"^[a-z]{2,20}$")


def validate(records: list[dict[str, Any]]) -> None:
    """Raise ValueError unless `records` is a well-formed affiliate list."""
    if not records:
        raise ValueError("FIK affiliate list is empty")
    seen_keys: set[str] = set()
    seen_names: set[str] = set()
    for record in records:
        if set(record) != set(FIELDS):
            raise ValueError(f"FIK affiliate has fields {sorted(record)}: {record}")
        key, name, iso = record["source_key"], record["name"], record["iso_code"]
        if not isinstance(name, str) or not name.strip() or len(name) > 255:
            raise ValueError(f"FIK affiliate {key!r} has a bad name: {name!r}")
        if record["type"] not in TYPES:
            raise ValueError(f"FIK affiliate {name!r} has type {record['type']!r}")
        if record["continental_grouping"] not in GROUPINGS:
            raise ValueError(
                f"FIK affiliate {name!r} has grouping "
                f"{record['continental_grouping']!r}"
            )
        national = record["type"] in ("National", "Special Status")
        if national:
            if not isinstance(iso, str) or not _ISO.match(iso) or key != iso:
                raise ValueError(f"FIK affiliate {name!r} has ISO code {iso!r}")
        elif iso is not None or not isinstance(key, str) or not _SLUG.match(key):
            raise ValueError(f"FIK affiliate {name!r} has key {key!r}, ISO {iso!r}")
        website = record["website"]
        if website is not None:
            parsed = urlparse(website)
            if parsed.scheme != "https" or not parsed.netloc or len(website) > 512:
                raise ValueError(f"FIK affiliate {name!r} has website {website!r}")
        if key in seen_keys or name in seen_names:
            raise ValueError(f"FIK affiliate {name!r} ({key}) is listed twice")
        seen_keys.add(key)
        seen_names.add(name)


def load(path: Path = CATALOGUE_PATH) -> list[dict[str, Any]]:
    """The bundled affiliate list, validated."""
    records = json.loads(path.read_text(encoding="utf-8"))
    validate(records)
    return records


async def sync(session: AsyncSession, records: list[dict[str, Any]]) -> None:
    """Bring the catalogue's FIK rows in line with `records`. Idempotent;
    flushes but does not commit.

    Raises RuntimeError, before writing anything, if an affiliate's name is
    already taken by a row the sync does not own: it never guesses whether
    that row is the same federation.
    """
    validate(records)
    rows = (await session.execute(select(Federation))).scalars().all()
    owned = {r.source_key: r for r in rows if r.source == SOURCE}
    others = {r.name: r for r in rows if r.source != SOURCE}
    for record in records:
        if record["name"] in others:
            raise RuntimeError(
                f"Federation {record['name']!r} (id {others[record['name']].id}) "
                "was not added by the FIK sync but has the name of a FIK "
                "affiliate. Rename or remove it, then re-run kendo-migrate."
            )
    wanted = {r["source_key"] for r in records}
    for key, row in owned.items():
        if key not in wanted:
            row.is_active = False
    for record in records:
        fields = {f: record[f] for f in FIELDS}
        row = owned.get(record["source_key"])
        if row is None:
            session.add(Federation(source=SOURCE, **fields))
        else:
            for field, value in fields.items():
                setattr(row, field, value)
    await session.flush()
